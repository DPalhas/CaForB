"use client";

import { TrendingUp, TrendingDown, Minus, ArrowRight } from "lucide-react";
import type { Insight } from "@/lib/types";
import { Badge } from "@/components/ui/badge";
import ScoreCard from "./ScoreCard";
import OpportunitiesList from "./OpportunitiesList";
import NextStepsList from "./NextStepsList";
import WeaknessesList from "./WeaknessesList";

interface ReportColumnProps {
  insight: Insight;
  modelLabel: string;
  isPrimary: boolean;
  onSetPrimary: (() => void) | null;
  onAskOpportunity: (opp: { id: string; title: string }) => void;
  onAskNextStep: (step: { id: string; action: string }) => void;
  onAskWeakness: (weakness: { index: number; text: string }) => void;
}

export default function ReportColumn({
  insight,
  modelLabel,
  isPrimary,
  onSetPrimary,
  onAskOpportunity,
  onAskNextStep,
  onAskWeakness,
}: ReportColumnProps) {
  return (
    <div className="space-y-6">
      {/* Model header */}
      <div className="flex items-center justify-between gap-3 rounded-xl border border-stone-800/80 bg-stone-900/40 px-4 py-3">
        <div className="min-w-0">
          <div className="text-xs uppercase tracking-wider text-stone-500 font-semibold">
            Generated by
          </div>
          <div className="truncate text-sm font-bold text-white">{modelLabel}</div>
        </div>
        {isPrimary ? (
          <Badge variant="primary" className="shrink-0 px-3 uppercase tracking-wider">
            Primary
          </Badge>
        ) : onSetPrimary ? (
          <button
            onClick={onSetPrimary}
            className="shrink-0 rounded-full border border-amber-500/50 px-3 py-1 text-xs font-bold uppercase tracking-wider text-amber-300 transition hover:bg-amber-950/40"
          >
            Set as primary
          </button>
        ) : null}
      </div>

      {insight.innovationScore !== null && insight.innovationScore !== undefined && (
        <ScoreCard score={insight.innovationScore} />
      )}

      <OpportunitiesList opportunities={insight.opportunities ?? []} onAsk={onAskOpportunity} />

      <NextStepsList steps={insight.nextSteps ?? []} onAsk={onAskNextStep} />

      <WeaknessesList weaknesses={insight.keyWeaknesses ?? []} onAsk={onAskWeakness} />

      {insight.comparisonToPrevious && (
        <div className="rounded-xl border border-stone-800/80 bg-stone-900/60 p-6 shadow-sm space-y-4">
          <h2 className="text-xl font-semibold text-white flex items-center gap-2">
            {insight.scoreDelta !== null && insight.scoreDelta > 0 ? (
              <TrendingUp className="w-5 h-5 text-emerald-400" />
            ) : insight.scoreDelta !== null && insight.scoreDelta < 0 ? (
              <TrendingDown className="w-5 h-5 text-rose-400" />
            ) : (
              <Minus className="w-5 h-5 text-amber-400" />
            )}
            vs. Previous Assessment #{insight.comparisonToPrevious.assessmentNumber}
          </h2>

          <div className="flex items-center justify-center gap-4 p-4 rounded-xl bg-stone-900/40 border border-stone-800/60">
            <div className="text-center">
              <div className="text-xs text-stone-500 mb-1">Previous</div>
              <div className="text-xl font-bold text-stone-400">
                {insight.comparisonToPrevious.previousScore?.toFixed(1) ?? "—"}
              </div>
              <div className="text-xs text-stone-500">
                {insight.comparisonToPrevious.previousDate}
              </div>
            </div>
            <ArrowRight className="w-5 h-5 text-stone-500" />
            <div className="text-center">
              <div className="text-xs text-stone-500 mb-1">Current</div>
              <div className="text-xl font-bold text-white">
                {insight.innovationScore?.toFixed(1) ?? "—"}
              </div>
              {insight.scoreDelta !== null && (
                <div className={`text-xs font-bold ${
                  insight.scoreDelta > 0 ? "text-emerald-400" : insight.scoreDelta < 0 ? "text-rose-400" : "text-amber-400"
                }`}>
                  {insight.scoreDelta > 0 ? "+" : ""}{insight.scoreDelta.toFixed(1)}
                </div>
              )}
            </div>
          </div>

          {insight.comparisonToPrevious.keyChanges && (
            <p className="text-sm text-stone-400 leading-relaxed">
              {insight.comparisonToPrevious.keyChanges}
            </p>
          )}
        </div>
      )}

      {insight.progress && (
        <div className="rounded-xl border border-stone-800/80 bg-stone-900/60 p-6 shadow-sm space-y-4">
          <h2 className="text-xl font-semibold text-white">Progress Report</h2>

          {(insight.progress.improvements ?? []).length > 0 && (
            <div>
              <h3 className="text-sm font-semibold text-emerald-400 mb-2">Improvements</h3>
              <ul className="space-y-1">
                {insight.progress.improvements.map((item: string, i: number) => (
                  <li key={i} className="text-sm text-stone-300 flex items-start gap-2">
                    <span className="text-emerald-500 mt-1">+</span>
                    {item}
                  </li>
                ))}
              </ul>
            </div>
          )}

          {(insight.progress.persistentGaps ?? []).length > 0 && (
            <div>
              <h3 className="text-sm font-semibold text-amber-400 mb-2">Persistent Gaps</h3>
              <ul className="space-y-1">
                {insight.progress.persistentGaps.map((item: string, i: number) => (
                  <li key={i} className="text-sm text-stone-300 flex items-start gap-2">
                    <span className="text-amber-500 mt-1">~</span>
                    {item}
                  </li>
                ))}
              </ul>
            </div>
          )}

          {(insight.progress.achievedMilestones ?? []).length > 0 && (
            <div>
              <h3 className="text-sm font-semibold text-blue-400 mb-2">Achieved Milestones</h3>
              <ul className="space-y-1">
                {insight.progress.achievedMilestones.map((item: string, i: number) => (
                  <li key={i} className="text-sm text-stone-300 flex items-start gap-2">
                    <span className="text-blue-500 mt-1">&#10003;</span>
                    {item}
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
